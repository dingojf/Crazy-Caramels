-- Run this in Supabase SQL Editor. Orders intentionally collect no customer personal information.
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  items jsonb not null,
  total numeric(10,2) not null,
  status text not null default 'new' check (status in ('new','done')),
  created_at timestamptz not null default now()
);
alter table public.orders enable row level security;
drop policy if exists "Public can place orders" on public.orders;
create policy "Public can place orders" on public.orders for insert to anon with check (true);
drop policy if exists "Public can view orders" on public.orders;
create policy "Public can view orders" on public.orders for select to anon using (true);
drop policy if exists "Public can mark orders completed" on public.orders;
create policy "Public can mark orders completed" on public.orders for update to anon using (true) with check (true);
alter table public.orders replica identity full;
do $$ begin
  alter publication supabase_realtime add table public.orders;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
