-- Crazy Caramels reviews: public reviews never expose customer email.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  rating smallint not null check (rating between 1 and 5),
  review text not null check (char_length(trim(review)) between 3 and 1000),
  email text not null check (char_length(email) between 5 and 254),
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;
revoke all on public.reviews from anon, authenticated;
grant insert on public.reviews to anon;
grant select on public.reviews to authenticated;

drop policy if exists "Customers can submit reviews" on public.reviews;
create policy "Customers can submit reviews"
  on public.reviews for insert to anon
  with check (
    rating between 1 and 5
    and char_length(trim(review)) between 3 and 1000
    and char_length(email) between 5 and 254
  );

drop policy if exists "Signed-in admins can read reviews" on public.reviews;
create policy "Signed-in admins can read reviews"
  on public.reviews for select to authenticated
  using (auth.uid() is not null);

-- This view intentionally contains no email addresses.
create or replace view public.public_reviews as
  select id, rating, review, created_at
  from public.reviews
  order by created_at desc;

grant select on public.public_reviews to anon, authenticated;
